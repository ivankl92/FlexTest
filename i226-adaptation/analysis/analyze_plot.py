#!/usr/bin/env python3
"""
analyze_plot.py - turn a TSN-FlexTest I226 measurement campaign into statistics
and figures.

Input : a results directory produced by run_measurement.sh, containing one
        subdirectory per measurement point with tx.csv, rx.csv and meta.json.
Output: summary.csv, summary.md and a set of PNG/PDF figures in <results>/figures/.

One-way latency = hardware RX timestamp (PC2 PHC) - hardware TX timestamp
(PC1 PHC), joined on the sequence number carried in the frame. Both PHCs are
disciplined by gPTP to the same grandmaster, so the difference is a true
NIC-to-NIC latency; any residual grandmaster offset shows up as a constant bias,
not as jitter.

Usage:
    python3 analyze_plot.py /path/to/results/<run-id>
    python3 analyze_plot.py /path/to/results/<run-id> --show-timeseries
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib

