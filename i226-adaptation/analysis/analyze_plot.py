# --- design tokens ---------------------------------------------------------
# Two categorical slots from the validated reference palette (blue, orange).
# Validated: adjacent CVD dE 24.7, normal-vision dE 33.6, contrast >= 3:1.
SERIES = {
    "none":  {"color": "#2a78d6", "label": "No-QoS (PCP 0)",      "marker": "o"},
    "dot1p": {"color": "#eb6834", "label": "IEEE 802.1p (PCP 6)", "marker": "s"},
}
INK_PRIMARY = "#0b0b0b"
INK_SECONDARY = "#52514e"
INK_MUTED = "#8a8984"

# A 2px surface-coloured halo keeps direct labels legible where they cross a mark.
HALO = [pe.withStroke(linewidth=3, foreground="#fcfcfb")]
